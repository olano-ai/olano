/**
 * Substitute `{name}` placeholders.
 *
 * `replaceAll`, not `replace`: a message is free to name the same value twice
 * ("{asker} asked {name}, and it answers inside {asker}'s reply"), and the
 * single-shot version left every repeat on screen as a literal `{asker}` —
 * which is what `addbot.whoHelp` and `ob.acct.doneNotSignedIn` were already
 * printing. The function form of the replacement is deliberate too: a string
 * replacement treats `$&` and `$1` in the VALUE as references, so a bot named
 * with a `$` would mangle itself.
 */
function fill(text: string, vars: Record<string, string>): string {
  let out = text;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, () => v);
  return out;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang());

  // Apply lang/dir on mount too, so a persisted non-English (or RTL) choice
  // is reflected on <html> before the user touches the language menu again.
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL_LANGS.has(lang) ? "rtl" : "ltr";
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const setLang = useCallback((next: Lang) => {
    localStorage.setItem(KEY, next);
    document.documentElement.lang = next;
    document.documentElement.dir = RTL_LANGS.has(next) ? "rtl" : "ltr";
    setLangState(next);
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string>) => {
      let s = DICTS[lang][key] ?? en[key] ?? key;
      if (vars) s = fill(s, vars);
      return s;
    },
    [lang],
  );

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used within <I18nProvider>");
  return ctx;
}

// Per-view translations: define a module-level dict and call useT(dict) to get a
// `t` that prefers the view's strings, then falls back to the shared dictionary,
// then the key. Keeps i18n local to each view instead of one giant central file.
export type LocalDict = Partial<Record<Lang, Record<string, string>>>;

/**
 * The local-dict half of useT's lookup, without the hook: the requested
 * language, then English, then undefined so the caller can fall back to the
 * central dictionary. Exported because core/settingsIndex resolves labels for
 * entries whose owning view is in another chunk and has no React context to
 * read — one fallback rule, used from both places.
 */
export function resolveLocal(local: LocalDict | undefined, lang: Lang, key: string): string | undefined {
  return local?.[lang]?.[key] ?? local?.en?.[key];
}

export function useT(local: LocalDict) {
  const { lang, t } = useI18n();
  return useCallback(
    (key: string, vars?: Record<string, string>) => {
      const hit = resolveLocal(local, lang, key);
      if (hit === undefined) return t(key, vars);
      let s = hit;
      if (vars) s = fill(s, vars);
      return s;
    },
    [lang, t, local],
  );
}
