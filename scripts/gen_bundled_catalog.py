#!/usr/bin/env python3
"""Regenerate olano/catalog/bundled.py from the cloud model catalog.

The bundled snapshot is the instant/offline baseline the dashboard and CLI
render before the disk cache or cloud sync has data. Refresh it at release
time so a fresh install starts from a recent catalog:

    python scripts/gen_bundled_catalog.py                 # from api.olano.ai
    python scripts/gen_bundled_catalog.py --url http://localhost:3000
    python scripts/gen_bundled_catalog.py --file payload.json

The payload is the ``GET /api/v1/models`` response shape. Entries are written
sparsely (defaults omitted) — ``models_registry`` normalizes on load.
"""

from __future__ import annotations

import argparse
import json
import pprint
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TARGET = REPO_ROOT / "olano" / "catalog" / "bundled.py"

# Defaults mirrored from models_registry — fields matching these are omitted
# from the generated literals to keep the module readable.
PROVIDER_DEFAULTS = {
    "package": None,
    "envVar": None,
    "docsUrl": None,
    "consoleUrl": None,
    "notes": None,
}
MODEL_DEFAULTS = {
    "displayName": None,
    "description": None,
    "family": None,
    "modality": "chat",
    "vision": False,
    "audioInput": False,
    "imageGen": False,
    "tts": False,
    "stt": False,
    "reasoning": False,
    "reasoningEfforts": [],
    "reasoningDefault": None,
    "contextWindow": None,
    "maxOutputTokens": None,
    "priceInput": None,
    "priceOutput": None,
    "priceCacheRead": None,
    "priceCacheWrite": None,
    "pricePerImage": None,
    "pricePerMinute": None,
    "tier": None,
    "recommended": False,
    "defaultForProvider": False,
    "deprecated": False,
    "eolDate": None,
    "metadata": {},
}

HEADER = '''"""Bundled offline snapshot of the cloud model catalog.

GENERATED by scripts/gen_bundled_catalog.py — do not edit by hand; refresh at
release time from the live catalog (see that script's docstring). This is the
known-good baseline rendered before the disk cache / cloud sync has data:
adding a model or changing a price is a cloud-side data change, no edit here.

Entries are sparse (defaults omitted); ``models_registry`` normalizes on load.
"""

from __future__ import annotations

from typing import Any

'''


def _sparse(entry: dict, defaults: dict, keep: tuple[str, ...]) -> dict:
    out = {k: entry[k] for k in keep if entry.get(k) not in (None, "")}
    for key, default in defaults.items():
        value = entry.get(key)
        if value is not None and value != default:
            out[key] = value
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default="https://api.olano.ai")
    parser.add_argument("--file", help="read a saved GET /api/v1/models payload instead")
    args = parser.parse_args()

    if args.file:
        payload = json.loads(Path(args.file).read_text())
    else:
        import httpx

        resp = httpx.get(
            f"{args.url.rstrip('/')}/api/v1/models", params={"limit": 2000}, timeout=30
        )
        resp.raise_for_status()
        payload = resp.json()

    providers = [
        _sparse(p, PROVIDER_DEFAULTS, ("key", "name")) for p in payload.get("providers", [])
    ]
    models = [
        _sparse(m, MODEL_DEFAULTS, ("id", "provider", "model")) for m in payload.get("models", [])
    ]
    if not providers or not models:
        print("payload has no providers/models — refusing to write", file=sys.stderr)
        return 1

    body = [HEADER]
    body.append(
        f"BUNDLED_PROVIDERS: list[dict[str, Any]] = {pprint.pformat(providers, width=96, sort_dicts=False)}\n\n"
    )
    body.append(
        f"BUNDLED_MODELS: list[dict[str, Any]] = {pprint.pformat(models, width=96, sort_dicts=False)}\n"
    )
    TARGET.write_text("".join(body))
    print(f"wrote {TARGET}: {len(providers)} providers, {len(models)} models")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
