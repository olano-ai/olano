#!/usr/bin/env python3
"""Regenerate the offline MCP directory baseline from the cloud catalog.

    python scripts/gen_bundled_mcp.py                  # from api.olano.ai
    python scripts/gen_bundled_mcp.py --url http://localhost:3000
    python scripts/gen_bundled_mcp.py --file payload.json
    python scripts/gen_bundled_mcp.py --sync-ts        # re-emit TS, no network
    python scripts/gen_bundled_mcp.py --check          # drift guard, no network

**One source, two consumers.** ``olano/core/bundled_mcp.json`` is the source of
truth for the offline baseline. Python reads it directly; the dashboard cannot
(its Vite root and its Docker build context are both ``olano/dashboard_2.0/``,
which does not contain ``olano/core/``), so this script also emits a generated
TS module beside the dashboard's own fallback lists. ``--check`` re-derives that
module and exits non-zero if it has drifted, which is what makes the two
physically-separate files impossible to diverge in practice.

Before this, the two lists were hand-maintained and had: the same server under
two different ids (``parallel`` vs ``parallel-search``), four field
disagreements on that row, a category invented on one side only, and an entry
present in both fallbacks and in no cloud row at all.

**The snapshot stays curated.** The live catalog is hundreds of rows; this baseline is
small and is meant to be a known-good starting point, not a mirror. PINNED_SLUGS
decides *which* rows are in it; the fetch refreshes *their* field values. Add a
slug here to include it, and re-run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = REPO_ROOT / "olano" / "core" / "bundled_mcp.json"
TS_TARGET = (
    REPO_ROOT / "olano" / "dashboard_2.0" / "src" / "views" / "agents" / "mcpBundled.generated.ts"
)

# Which rows the offline baseline carries. Order is the order they render in.
PINNED_SLUGS: tuple[str, ...] = (
    # presets — "Connect a service" buttons
    "hubspot",
    "stripe",
    "notion",
    "linear",
    "sentry",
    "github",
    "intercom",
    "paypal",
    "square",
    "canva",
    "webflow",
    "wix",
    "asana",
    "atlassian",
    "vercel",
    "zapier",
    "parallel",
    "parallel-task",
    "composio",
    "huggingface",
    "deepwiki",
    "cloudflare-docs",
    "microsoft-learn",
    "supabase",
    # examples — copy-paste starters, including local stdio servers
    "everything-stdio",
    "time-python-stdio",
    "everything-sse",
    "everything-http",
    "stripe-example",
    "github-docker-stdio",
)

TS_HEADER = """// GENERATED by scripts/gen_bundled_mcp.py — do not edit by hand.
//
// The offline baseline for the MCP directory, in the cloud's wire shape. Its
// source of truth is olano/core/bundled_mcp.json, which the Python runtime
// reads directly; this file exists because the dashboard's Vite root and Docker
// build context are both olano/dashboard_2.0/ and cannot reach olano/core/.
// `gen_bundled_mcp.py --check` fails CI if the two drift.
//
// mcpPresets.ts / mcpDirectory.ts convert these rows into the dashboard's own
// McpPreset / McpExample shapes through toPreset() / toExample(); do not add a
// second converter here.

export interface BundledServer {
  slug: string;
  name: string;
  kind: "preset" | "example";
  description?: string | null;
  category?: string | null;
  transport?: string | null;
  auth?: string;
  oauthClient?: string | null;
  url?: string | null;
  command?: string | null;
  args?: string[];
  envKeys?: string[];
  logoUrl?: string | null;
  homepageUrl?: string | null;
  docsUrl?: string | null;
  appConsoleUrl?: string | null;
  appConsoleLabel?: string | null;
  badge?: string | null;
  runCommand?: string | null;
  exampleJson?: string | null;
  notes?: string | null;
  featured?: boolean;
}

export const BUNDLED_SERVERS: BundledServer[] = """

SNAPSHOT_COMMENT = (
    "SOURCE OF TRUTH for the offline MCP directory baseline. Do not hand-edit: "
    "regenerate with `uv run python scripts/gen_bundled_mcp.py`. Shape is the "
    "cloud's GET /api/v1/mcp response filtered to the pinned slugs, written "
    "sparsely (fields equal to the normalizer's defaults are omitted)."
)


def _entry_defaults() -> dict[str, Any]:
    sys.path.insert(0, str(REPO_ROOT))
    from olano.core.mcp_registry import _ENTRY_DEFAULTS

    return dict(_ENTRY_DEFAULTS)


# Always written out, even when it equals the default: `kind` is what splits the
# flat list into presets and examples on both sides, so a row that omits it is
# not self-describing — and the TS type declares it required.
_ALWAYS_KEEP = frozenset({"slug", "name", "kind"})


def _sparse(row: dict[str, Any], defaults: dict[str, Any]) -> dict[str, Any]:
    """Drop fields equal to the normalizer's default; it fills them on load."""
    return {
        k: row[k] for k in defaults if k in row and (k in _ALWAYS_KEEP or row[k] != defaults[k])
    }


def _fetch(url: str) -> list[dict[str, Any]]:
    import httpx

    servers: list[dict[str, Any]] = []
    offset = 0
    with httpx.Client(timeout=30.0) as client:
        while True:
            resp = client.get(f"{url}/api/v1/mcp", params={"limit": 200, "offset": offset})
            resp.raise_for_status()
            data = resp.json()
            page = data.get("servers") or []
            servers.extend(page)
            total = data.get("total")
            if not page or not isinstance(total, int) or len(servers) >= total:
                return servers
            offset = len(servers)


def _render_snapshot(rows: list[dict[str, Any]]) -> str:
    payload = {"_comment": SNAPSHOT_COMMENT, "servers": rows}
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _render_ts(rows: list[dict[str, Any]]) -> str:
    return TS_HEADER + json.dumps(rows, indent=2, ensure_ascii=False) + ";\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--url", default="https://api.olano.ai", help="cloud API base URL")
    ap.add_argument("--file", help="read a GET /api/v1/mcp payload from disk instead")
    ap.add_argument(
        "--sync-ts",
        action="store_true",
        help="re-emit the TS module from the committed snapshot; no network",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the committed TS module matches the snapshot; no network, no writes",
    )
    args = ap.parse_args()
    defaults = _entry_defaults()

    if args.check or args.sync_ts:
        if not SNAPSHOT.exists():
            print(f"missing {SNAPSHOT}", file=sys.stderr)
            return 1
        rows = json.loads(SNAPSHOT.read_text(encoding="utf-8"))["servers"]
        want = _render_ts(rows)
        if args.sync_ts:
            TS_TARGET.write_text(want, encoding="utf-8")
            print(f"wrote {TS_TARGET.relative_to(REPO_ROOT)} ({len(rows)} rows)")
            return 0
        have = TS_TARGET.read_text(encoding="utf-8") if TS_TARGET.exists() else ""
        if want != have:
            print(
                f"{TS_TARGET.relative_to(REPO_ROOT)} is stale — regenerate with:\n"
                "    uv run python scripts/gen_bundled_mcp.py --sync-ts",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {TS_TARGET.relative_to(REPO_ROOT)} matches the snapshot ({len(rows)} rows)")
        return 0

    if args.file:
        payload = json.loads(Path(args.file).read_text(encoding="utf-8"))
        fetched = payload.get("servers") if isinstance(payload, dict) else payload
    else:
        fetched = _fetch(args.url.rstrip("/"))

    by_slug = {str(s.get("slug")): s for s in fetched if isinstance(s, dict)}
    missing = [s for s in PINNED_SLUGS if s not in by_slug]
    if missing:
        # Refuse rather than silently shrink the baseline — a pinned slug the
        # catalog no longer serves is a decision, not a generation detail.
        print(f"pinned slugs missing from the catalog: {', '.join(missing)}", file=sys.stderr)
        return 1

    rows = [_sparse(by_slug[slug], defaults) for slug in PINNED_SLUGS]
    SNAPSHOT.write_text(_render_snapshot(rows), encoding="utf-8")
    TS_TARGET.write_text(_render_ts(rows), encoding="utf-8")
    print(f"wrote {SNAPSHOT.relative_to(REPO_ROOT)} and {TS_TARGET.relative_to(REPO_ROOT)}")
    print(
        f"  {len(rows)} rows: {sum(1 for r in rows if r.get('kind') != 'example')} presets, "
        f"{sum(1 for r in rows if r.get('kind') == 'example')} examples"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
