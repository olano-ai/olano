"""Regenerate olano/tools/_name_index.py — the static tool-name index.

The registry resolves tool names lazily: a name found in the generated index
imports only the toolkit module that owns it, instead of importing every
toolkit (~75 modules, ~650 tool constructions, several seconds) to build the
name map at runtime. See ``olano/tools/registry.py:_resolve_name``.

Run after adding, removing, or renaming a tool or toolkit:

    uv run python scripts/gen_tool_name_index.py

``tests/test_tool_name_index.py`` fails when this file is stale.
"""

from __future__ import annotations

import importlib
import sys
from pathlib import Path

OUT_PATH = Path(__file__).resolve().parents[1] / "olano" / "tools" / "_name_index.py"

HEADER = '''"""GENERATED FILE — do not edit by hand.

Static tool-name → toolkit-module index, generated by
``scripts/gen_tool_name_index.py`` from the live registry scan. It lets
``registry._resolve_name`` import only the toolkit that owns a requested tool
instead of importing every toolkit to find out who owns what (the difference
between a ~0.1s and a ~2.5s agent build).

Names missing here still resolve — the registry falls back to the full scan —
so a stale index is a performance regression, not a breakage.
``tests/test_tool_name_index.py`` guards against drift; regenerate with:

    uv run python scripts/gen_tool_name_index.py
"""

from __future__ import annotations

NAME_INDEX: dict[str, str] = {
'''


def scan() -> dict[str, str]:
    """The same walk ``registry._ensure_index`` performs, name → module path."""
    from olano.tools.registry import _TOOLKITS

    index: dict[str, str] = {}
    failures: list[str] = []
    for toolkit, mod_path in _TOOLKITS.items():
        try:
            mod = importlib.import_module(mod_path)
            tools = mod.get_tools()
        except Exception as e:
            failures.append(f"{toolkit} ({mod_path}): {e}")
            continue
        for t in tools:
            name = getattr(t, "name", None)
            if name:
                index[name] = mod_path
    if failures:
        # A toolkit that doesn't import in the dev env would silently vanish
        # from the index — that must be a hard error here, not a skip.
        print("ERROR: toolkits failed to import:", file=sys.stderr)
        for f in failures:
            print(f"  {f}", file=sys.stderr)
        raise SystemExit(1)
    return index


def render(index: dict[str, str]) -> str:
    lines = [HEADER]
    for name in sorted(index):
        lines.append(f'    "{name}": "{index[name]}",\n')
    lines.append("}\n")
    return "".join(lines)


def main() -> None:
    index = scan()
    OUT_PATH.write_text(render(index), encoding="utf-8")
    print(f"wrote {len(index)} tool names to {OUT_PATH}")


if __name__ == "__main__":
    main()
